using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;

Console.OutputEncoding = Encoding.UTF8;

if (args.Length < 2)
{
    Console.WriteLine("Usage: convert <quiz-data.json> <output-dir>");
    return 1;
}

var sourcePath = args[0];
var outputDir = args[1];
var imagesDir = Path.Combine(outputDir, "images");

var stateCodes = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
{
    ["baden-wuerttemberg"] = "BW",
    ["bayern"] = "BY",
    ["berlin"] = "BE",
    ["brandenburg"] = "BB",
    ["bremen"] = "HB",
    ["hamburg"] = "HH",
    ["hessen"] = "HE",
    ["mecklenburg-vorpommern"] = "MV",
    ["niedersachsen"] = "NI",
    ["nordrhein-westfalen"] = "NW",
    ["rheinland-pfalz"] = "RP",
    ["saarland"] = "SL",
    ["sachsen"] = "SN",
    ["sachsen-anhalt"] = "ST",
    ["schleswig-holstein"] = "SH",
    ["thueringen"] = "TH"
};

using var document = JsonDocument.Parse(File.ReadAllText(sourcePath));
var root = document.RootElement;
var sourceVersion = root.TryGetProperty("version", out var versionElement) ? versionElement.GetString() : null;

var federal = new List<Question>();
foreach (var item in root.GetProperty("general").EnumerateArray())
{
    var number = item.GetProperty("id").GetInt32();
    federal.Add(ReadQuestion(item, $"B{number:000}", number, TopicFor(number), null));
}

var states = new Dictionary<string, List<Question>>(StringComparer.Ordinal);
foreach (var stateProperty in root.GetProperty("states").EnumerateObject())
{
    var slug = stateProperty.Name;
    if (!stateCodes.TryGetValue(slug, out var code))
    {
        throw new InvalidOperationException($"Unknown state slug: {slug}");
    }

    var questions = new List<Question>();
    var index = 1;
    foreach (var item in stateProperty.Value.GetProperty("questions").EnumerateArray())
    {
        questions.Add(ReadQuestion(item, $"{code}{index:00}", index, "state", code));
        index++;
    }

    if (questions.Count != 10)
    {
        throw new InvalidOperationException($"{slug} has {questions.Count} questions (expected 10)");
    }

    states[code] = questions;
}

if (federal.Count != 300)
{
    throw new InvalidOperationException($"Federal pool has {federal.Count} questions (expected 300)");
}

if (states.Count != 16)
{
    throw new InvalidOperationException($"Found {states.Count} states (expected 16)");
}

var problems = new List<string>();
Validate(federal, states, problems);
foreach (var missing in FindMissingImages(federal, states, imagesDir))
{
    problems.Add($"Missing image file: {missing}");
}

if (problems.Count > 0)
{
    Console.WriteLine("VALIDATION FAILED:");
    foreach (var problem in problems)
    {
        Console.WriteLine("  - " + problem);
    }

    return 2;
}

var output = new JsonObject
{
    ["version"] = sourceVersion,
    ["generated"] = DateTime.UtcNow.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
    ["source"] = new JsonObject
    {
        ["catalog"] = "https://www.bamf.de/SharedDocs/Anlagen/DE/Integration/Einbuergerung/gesamtfragenkatalog-lebenindeutschland.pdf?__blob=publicationFile&v=23",
        ["catalogVersion"] = "2025-05-07",
        ["catalogSha256"] = "EDD3ED5E56A35241B6CC61AA0630482DC9E64498DB508A7D6892CCEE2EC707A9",
        ["dataset"] = "https://github.com/abdullahbutt/leben-in-deutschland-test",
        ["datasetVersion"] = sourceVersion,
        ["license"] = "CC BY-NC 4.0",
        ["attribution"] = "Fragen: Bundesamt für Migration und Flüchtlinge (BAMF). Englische Übersetzungen und Erläuterungen: Abdullah Butt, CC BY-NC 4.0. Bilder: BAMF-Fragenkatalog bzw. o. g. Datensatz."
    },
    ["general"] = new JsonArray(federal.Select(ToJson).ToArray()),
    ["states"] = new JsonObject(states.Select(pair =>
        new KeyValuePair<string, JsonNode?>(pair.Key, new JsonArray(pair.Value.Select(ToJson).ToArray()))))
};

var options = new JsonSerializerOptions
{
    Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    WriteIndented = false
};

var json = output.ToJsonString(options).Replace("</", "<\\/", StringComparison.Ordinal);

Directory.CreateDirectory(outputDir);
var questionsPath = Path.Combine(outputDir, "questions.js");
File.WriteAllText(questionsPath,
    "/* Auto-generated by tools/Convert - do not edit manually. */\nwindow.EINBUERGERUNG_DATA = " + json + ";\n",
    new UTF8Encoding(false));

var summary = new JsonObject
{
    ["version"] = sourceVersion,
    ["general"] = federal.Count,
    ["states"] = new JsonObject(states.Select(pair =>
        new KeyValuePair<string, JsonNode?>(pair.Key, pair.Value.Count))),
    ["stateTotal"] = states.Values.Sum(list => list.Count),
    ["withImage"] = federal.Concat(states.Values.SelectMany(list => list)).Count(q => q.Image is not null),
    ["topics"] = new JsonObject(new[]
    {
        new KeyValuePair<string, JsonNode?>("democracy", federal.Count(q => q.Topic == "democracy")),
        new KeyValuePair<string, JsonNode?>("history", federal.Count(q => q.Topic == "history")),
        new KeyValuePair<string, JsonNode?>("society", federal.Count(q => q.Topic == "society")),
        new KeyValuePair<string, JsonNode?>("state", states.Values.Sum(list => list.Count))
    })
};
File.WriteAllText(Path.Combine(outputDir, "summary.json"),
    summary.ToJsonString(new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }),
    new UTF8Encoding(false));

var csv = new StringBuilder();
csv.AppendLine("id;topic;bamfNo;state;question;optionA;optionB;optionC;optionD;correct;image;explanation");
foreach (var question in federal.Concat(states.Values.SelectMany(list => list)))
{
    csv.AppendLine(string.Join(";", new[]
    {
        Csv(question.Id),
        Csv(question.Topic),
        question.BamfNo.ToString(CultureInfo.InvariantCulture),
        Csv(question.State ?? ""),
        Csv(question.De),
        Csv(question.Options[0].De),
        Csv(question.Options[1].De),
        Csv(question.Options[2].De),
        Csv(question.Options[3].De),
        (question.Correct + 1).ToString(CultureInfo.InvariantCulture),
        Csv(question.Image ?? ""),
        Csv(question.ExplanationDe)
    }));
}

File.WriteAllText(Path.Combine(outputDir, "review.csv"), csv.ToString(), new UTF8Encoding(true));

Console.WriteLine($"Wrote {questionsPath} ({new FileInfo(questionsPath).Length:N0} bytes)");
Console.WriteLine($"General: {federal.Count}, State: {states.Values.Sum(list => list.Count)}, Images: {federal.Concat(states.Values.SelectMany(list => list)).Count(q => q.Image is not null)}");
Console.WriteLine("Topics: " + string.Join(", ", new[] { "democracy", "history", "society" }.Select(topic => $"{topic}={federal.Count(q => q.Topic == topic)}")));
return 0;

static Question ReadQuestion(JsonElement item, string id, int bamfNo, string topic, string? state)
{
    var options = item.GetProperty("options").EnumerateArray().ToList();
    var question = new Question
    {
        Id = id,
        BamfNo = bamfNo,
        Topic = topic,
        State = state,
        De = Required(item, "de"),
        En = Required(item, "en"),
        Correct = item.GetProperty("correct").GetInt32(),
        ExplanationDe = Required(item, "exp_de"),
        ExplanationEn = Required(item, "exp_en"),
        Image = item.TryGetProperty("image", out var image) && image.ValueKind == JsonValueKind.String
            ? "data/images/" + Path.GetFileName(image.GetString())
            : null
    };

    foreach (var option in options)
    {
        question.Options.Add(new Option
        {
            De = Required(option, "de"),
            En = Required(option, "en")
        });
    }

    return question;

    static string Required(JsonElement element, string property)
    {
        var value = element.GetProperty(property).GetString();
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new InvalidOperationException($"Missing '{property}' value");
        }

        return value.Trim();
    }
}

static string TopicFor(int number) => number switch
{
    <= 150 => "democracy",
    <= 250 => "history",
    _ => "society"
};

static JsonObject ToJson(Question question)
{
    var obj = new JsonObject
    {
        ["id"] = question.Id,
        ["bamfNo"] = question.BamfNo,
        ["topic"] = question.Topic,
        ["de"] = question.De,
        ["en"] = question.En,
        ["optionsDe"] = new JsonArray(question.Options.Select(option => (JsonNode?)JsonValue.Create(option.De)).ToArray()),
        ["optionsEn"] = new JsonArray(question.Options.Select(option => (JsonNode?)JsonValue.Create(option.En)).ToArray()),
        ["correct"] = question.Correct,
        ["image"] = question.Image,
        ["expDe"] = question.ExplanationDe,
        ["expEn"] = question.ExplanationEn
    };

    if (question.State is not null)
    {
        obj["state"] = question.State;
    }

    return obj;
}

static void Validate(List<Question> federal, Dictionary<string, List<Question>> states, List<string> problems)
{
    var all = federal.Concat(states.Values.SelectMany(list => list)).ToList();
    var ids = new HashSet<string>(StringComparer.Ordinal);
    var signatures = new HashSet<string>(StringComparer.Ordinal);

    foreach (var question in all)
    {
        if (!ids.Add(question.Id))
        {
            problems.Add($"Duplicate id: {question.Id}");
        }

        if (question.Options.Count != 4)
        {
            problems.Add($"{question.Id}: {question.Options.Count} options");
        }

        if (question.Correct < 0 || question.Correct >= question.Options.Count)
        {
            problems.Add($"{question.Id}: correct index {question.Correct} out of range");
        }

        var signature = Normalize(question.De) + "|" +
                        string.Join("|", question.Options.Select(option => Normalize(option.De))) + "|" +
                        question.Correct;
        if (!signatures.Add(signature))
        {
            problems.Add($"{question.Id}: identical question (same text, options and answer)");
        }

        if (question.Options.Select(option => Normalize(option.De)).Distinct().Count() != question.Options.Count)
        {
            problems.Add($"{question.Id}: duplicate option text");
        }
    }

    if (federal.Count(q => q.Topic == "democracy") < 18 ||
        federal.Count(q => q.Topic == "history") < 9 ||
        federal.Count(q => q.Topic == "society") < 3)
    {
        problems.Add("A topic pool is too small for the 18/9/3 blueprint");
    }
}

static List<string> FindMissingImages(List<Question> federal, Dictionary<string, List<Question>> states, string imagesDir)
{
    return federal.Concat(states.Values.SelectMany(list => list))
        .Select(question => question.Image)
        .Where(image => image is not null)
        .Select(image => Path.Combine(imagesDir, Path.GetFileName(image!)))
        .Where(path => !File.Exists(path))
        .ToList();
}

static string Normalize(string value)
{
    var builder = new StringBuilder(value.Length);
    foreach (var character in value.Normalize(NormalizationForm.FormC))
    {
        if (char.IsLetterOrDigit(character))
        {
            builder.Append(char.ToLowerInvariant(character));
        }
    }

    return builder.ToString();
}

static string Csv(string value) => "\"" + value.Replace("\"", "\"\"") + "\"";

internal sealed class Question
{
    public required string Id { get; init; }
    public required int BamfNo { get; init; }
    public required string Topic { get; init; }
    public string? State { get; init; }
    public required string De { get; init; }
    public required string En { get; init; }
    public required int Correct { get; init; }
    public string? Image { get; init; }
    public required string ExplanationDe { get; init; }
    public required string ExplanationEn { get; init; }
    public List<Option> Options { get; } = new();
}

internal sealed class Option
{
    public required string De { get; init; }
    public required string En { get; init; }
}
